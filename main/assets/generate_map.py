"""Generate the indexed Ukraine map used by the 480 × 480 dashboard."""

import argparse
from itertools import groupby
import json
import math
from pathlib import Path

WIDTH = 424
HEIGHT = 222
BORDER = 250
EXPECTED_REGIONS = {
    5, 7, 9, 12, 14, 18, 21, 23, 26, 30, 32, 35, 40, 43, 46, 48, 51, 53,
    56, 59, 61, 63, 65, 68, 71, 74, 77,
}


def rasterize(document):
    regions = {}
    points = []
    for feature in document["features"]:
        iso = feature["properties"]["shapeISO"]
        if not iso.startswith("UA-"):
            raise ValueError(f"Unexpected region: {iso}")
        region = int(iso[3:])
        geometry = feature["geometry"]
        if geometry["type"] == "Polygon":
            polygons = [geometry["coordinates"]]
        elif geometry["type"] == "MultiPolygon":
            polygons = geometry["coordinates"]
        else:
            raise ValueError(f"Unsupported geometry: {geometry['type']}")
        regions.setdefault(region, []).extend(polygons)
        points.extend(point for polygon in polygons for ring in polygon for point in ring)
    if set(regions) != EXPECTED_REGIONS:
        raise ValueError("Expected 27 Ukrainian regions, including Crimea and Sevastopol")

    west, east = min(p[0] for p in points), max(p[0] for p in points)
    south, north = min(p[1] for p in points), max(p[1] for p in points)
    longitude_scale = math.cos(math.radians((south + north) / 2))
    projected_width = (east - west) * longitude_scale
    scale = min((WIDTH - 4) / projected_width, (HEIGHT - 4) / (north - south))
    left = (WIDTH - projected_width * scale) / 2
    top = (HEIGHT - (north - south) * scale) / 2

    def project(point):
        lon, lat = point[:2]
        return left + (lon - west) * longitude_scale * scale, top + (north - lat) * scale

    pixels = bytearray(WIDTH * HEIGHT)
    for region, polygons in regions.items():
        for polygon in polygons:
            fill_polygon(pixels, [list(map(project, ring)) for ring in polygon], region)

    city_x, city_y = map(int, project((35.046, 48.4647)))
    if set(pixels) != EXPECTED_REGIONS | {0} or pixels[city_y * WIDTH + city_x] != 12:
        raise ValueError("Rasterization lost a region or misplaced Dnipro")

    outlined = pixels[:]
    for y in range(1, HEIGHT - 1):
        for x in range(1, WIDTH - 1):
            i = y * WIDTH + x
            value = pixels[i]
            if value and (
                pixels[i + 1] != value or pixels[i + WIDTH] != value
                or not pixels[i - 1] or not pixels[i - WIDTH]
            ):
                outlined[i] = BORDER
    if set(outlined) != EXPECTED_REGIONS | {0, BORDER}:
        raise ValueError("Outlines hid an administrative region")
    return outlined, city_x, city_y


def fill_polygon(pixels, rings, region):
    edges = [(a, b) for ring in rings for a, b in zip(ring, ring[1:])]
    start = max(0, math.floor(min(p[1] for ring in rings for p in ring)))
    end = min(HEIGHT, math.ceil(max(p[1] for ring in rings for p in ring)))
    for y in range(start, end):
        scan_y = y + 0.5
        crossings = sorted(
            x1 + (scan_y - y1) * (x2 - x1) / (y2 - y1)
            for (x1, y1), (x2, y2) in edges if (y1 > scan_y) != (y2 > scan_y)
        )
        for left, right in zip(crossings[::2], crossings[1::2]):
            first = max(0, math.ceil(left - 0.5))
            last = min(WIDTH, math.ceil(right - 0.5))
            pixels[y * WIDTH + first:y * WIDTH + last] = bytes([region]) * (last - first)


def generate_header(document):
    pixels, city_x, city_y = rasterize(document)
    lines = [
        "/* Generated by generate_map.py from geoBoundaries UKR-ADM1-14850775. */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"enum {{ UA_MAP_WIDTH = {WIDTH}, UA_MAP_HEIGHT = {HEIGHT}, UA_MAP_BORDER = {BORDER},",
        f"       UA_MAP_DNIPRO_X = {city_x}, UA_MAP_DNIPRO_Y = {city_y} }};",
        "",
        "/* Each row contains successive (length, palette index) pairs. */",
        "static const uint8_t ua_map_runs[] = {",
    ]
    for y in range(HEIGHT):
        row = pixels[y * WIDTH:(y + 1) * WIDTH]
        runs = []
        for value, group in groupby(row):
            length = sum(1 for _ in group)
            while length:
                chunk = min(length, 255)
                runs.extend((chunk, value))
                length -= chunk
        lines.append("    " + ", ".join(map(str, runs)) + ",")
    return "\n".join(lines + ["};", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("geojson", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    document = json.loads(args.geojson.read_text(encoding="utf-8-sig"))
    args.output.write_text(generate_header(document), encoding="utf-8", newline="\n")
